import { canvasTextFromPlainText } from './canvasText';
import { describe, expect, it } from 'vitest';
import { Editor } from './editor';
import { newDocument, resolveAnchor } from './document';

describe('时间锚点与撤销', () => {
  it('显示比例与裁剪相互独立，裁剪外连接可恢复', () => {
    const document = newDocument('测试');
    const assetId = crypto.randomUUID();
    const mediaId = crypto.randomUUID();
    document.assets.push({ id: assetId, name: 'test.wav', path: 'assets/test.wav', kind: 'audio', status: 'ready', durationUs: 10_000_000 });
    document.objects.push({ id: mediaId, kind: 'media', assetId, x: 10, y: 20, width: 300, height: 80, groupId: null, inUs: 0, outUs: 10_000_000, pixelsPerSecond: 30 });
    const editor = new Editor(document);
    const textId = editor.annotateMarker(editor.addMarker(mediaId, 5_000_000), { x: 400, y: 100 });
    const anchor = editor.document.connections[0].from;
    expect(resolveAnchor(editor.document, anchor)?.x).toBe(160);
    editor.execute(draft => { const media = draft.objects[0]; if (media.kind === 'media') media.pixelsPerSecond = 60; });
    expect(resolveAnchor(editor.document, anchor)?.x).toBe(310);
    editor.execute(draft => { const media = draft.objects[0]; if (media.kind === 'media') media.inUs = 6_000_000; });
    expect(resolveAnchor(editor.document, anchor)).toBeNull();
    editor.undo();
    expect(resolveAnchor(editor.document, anchor)?.x).toBe(310);
    editor.deleteObjects([textId]);
    expect(editor.document.markers).toHaveLength(1);
    expect(editor.document.connections).toHaveLength(0);
    editor.undo();
    expect(editor.document.connections).toHaveLength(1);
  });
  it('复制轨道同时复制标记和内部连接，原实例保持独立', () => {
    const document = newDocument('复制');
    const assetId = crypto.randomUUID(), mediaId = crypto.randomUUID(), textId = crypto.randomUUID();
    document.assets.push({ id: assetId, name: 'a.mp3', path: 'assets/a.mp3', kind: 'audio', status: 'ready' });
    document.objects.push({ id: mediaId, kind: 'media', assetId, x: 0, y: 0, width: 100, height: 80, groupId: null, inUs: 0, outUs: 5_000_000, pixelsPerSecond: 30 });
    document.objects.push({ id: textId, kind: 'text', x: 200, y: 0, width: 100, height: 50, groupId: null, text: canvasTextFromPlainText('说明'), fontSize: 16, color: '#000', align: 'left' });
    const editor = new Editor(document);
    editor.annotateMarker(editor.addMarker(mediaId, 2_000_000), textId);
    editor.duplicateObjects([mediaId, textId]);
    expect(editor.document.objects).toHaveLength(4);
    expect(editor.document.markers).toHaveLength(2);
    expect(editor.document.connections).toHaveLength(2);
    editor.deleteObjects([mediaId]);
    expect(editor.document.markers).toHaveLength(1);
    expect(editor.document.connections).toHaveLength(1);
  });
  it('连续预览只形成一次撤销和一次文档修订', () => {
    const editor = new Editor(newDocument('预览'));
    editor.preview(draft => { draft.camera.scale = 1.2; });
    editor.preview(draft => { draft.camera.scale = 1.5; });
    expect(editor.document.revision).toBe(0);
    editor.commitPreview();
    expect(editor.document.revision).toBe(1);
    editor.undo();
    expect(editor.document.camera.scale).toBe(1);
    editor.redo();
    expect(editor.document.camera.scale).toBe(1.5);
  });
  it('嵌套分组整体移动、解组和删除保持关系一致', () => {
    const document = newDocument('分组');
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    ids.forEach((id, index) => document.objects.push({ id, kind: 'rectangle', x: index * 100, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' }));
    const editor = new Editor(document);
    editor.group(ids.slice(0, 2));
    const parentId = editor.document.objects[0].groupId;
    editor.group(ids.slice(0, 2));
    const childId = editor.document.objects[0].groupId;
    expect(editor.document.groups.find(group => group.id === childId)?.parentId).toBe(parentId);
    editor.moveObject(ids[0], 200, 40);
    expect(editor.document.objects.map(item => [item.x, item.y])).toEqual([[200, 40], [300, 40], [200, 0]]);
    editor.undo();
    expect(editor.document.objects[0].x).toBe(0);
    editor.ungroup(childId!);
    expect(editor.document.objects[0].groupId).toBe(parentId);
    editor.deleteObjects(ids.slice(0, 2));
    expect(editor.document.groups).toHaveLength(0);
  });
  it('移动内层组时不会带动外层组的其他对象', () => {
    const document = newDocument('嵌套移动');
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    ids.forEach((id, index) => document.objects.push({ id, kind: 'rectangle', x: index * 100, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' }));
    const editor = new Editor(document);
    editor.group(ids);
    const outerId = editor.document.objects[0].groupId;
    editor.group(ids.slice(0, 2));
    const innerId = editor.document.objects[0].groupId;
    expect(editor.document.groups.find(group => group.id === innerId)?.parentId).toBe(outerId);
    editor.moveObject(ids[0], 40, 30);
    expect(editor.document.objects.map(item => [item.x, item.y])).toEqual([[40, 30], [140, 30], [200, 0]]);
  });
  it('已有组与普通对象再分组时保留原组成员和嵌套关系', () => {
    const document = newDocument('混合分组');
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    ids.forEach((id, index) => document.objects.push({ id, kind: 'rectangle', x: index * 100, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' }));
    const editor = new Editor(document);
    editor.group(ids.slice(0, 2));
    const innerId = editor.document.objects[0].groupId;
    editor.group([ids[0], ids[2]]);
    const outerId = editor.document.objects[2].groupId;
    expect(editor.document.objects[1].groupId).toBe(innerId);
    expect(editor.document.groups.find(group => group.id === innerId)?.parentId).toBe(outerId);
    editor.moveObject(ids[0], 40, 10);
    expect(editor.document.objects.map(item => [item.x, item.y])).toEqual([[40, 10], [140, 10], [200, 0]]);
    editor.moveObject(ids[2], 240, 20);
    expect(editor.document.objects.map(item => [item.x, item.y])).toEqual([[80, 30], [180, 30], [240, 20]]);
  });
  it('多选移动对同组成员只应用一次位移且只产生一次撤销', () => {
    const document = newDocument('多选移动');
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    ids.forEach((id, index) => document.objects.push({ id, kind: 'rectangle', x: index * 100, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' }));
    const editor = new Editor(document);
    editor.group(ids.slice(0, 2));
    const previousRevision = editor.document.revision;
    editor.moveObjects(ids, 20, 30);
    expect(editor.document.objects.map(item => [item.x, item.y])).toEqual([[20, 30], [120, 30], [220, 30]]);
    expect(editor.document.revision).toBe(previousRevision + 1);
    editor.undo();
    expect(editor.document.objects.map(item => [item.x, item.y])).toEqual([[0, 0], [100, 0], [200, 0]]);
  });
  it('被引用的素材不能移除，删除实例后移除仍可撤销', () => {
    const document = newDocument('素材');
    const assetId = crypto.randomUUID(), objectId = crypto.randomUUID();
    document.assets.push({ id: assetId, name: 'image.png', path: 'assets/image.png', kind: 'image', status: 'ready' });
    document.objects.push({ id: objectId, kind: 'image', assetId, x: 0, y: 0, width: 100, height: 100, groupId: null });
    const editor = new Editor(document);
    expect(() => editor.removeAsset(assetId)).toThrow('素材仍被画布对象引用');
    editor.deleteObjects([objectId]);
    editor.removeAsset(assetId);
    expect(editor.document.assets).toHaveLength(0);
    editor.undo();
    expect(editor.document.assets).toHaveLength(1);
  });
  it('移动标记保持时间锚点，删除标记同时删除相关连线且可撤销', () => {
    const document = newDocument('标记');
    const assetId = crypto.randomUUID(), mediaId = crypto.randomUUID();
    document.assets.push({ id: assetId, name: 'test.wav', path: 'assets/test.wav', kind: 'audio', status: 'ready' });
    document.objects.push({ id: mediaId, kind: 'media', assetId, x: 10, y: 0, width: 100, height: 80, groupId: null, inUs: 0, outUs: 10_000_000, pixelsPerSecond: 20 });
    const editor = new Editor(document);
    editor.annotateMarker(editor.addMarker(mediaId, 1_000_000), { x: 300, y: 0 });
    const markerId = editor.document.markers[0].id;
    editor.moveMarker(markerId, 3_000_000);
    expect(resolveAnchor(editor.document, editor.document.connections[0].from)?.x).toBe(70);
    editor.deleteMarker(markerId);
    expect(editor.document.markers).toHaveLength(0);
    expect(editor.document.connections).toHaveLength(0);
    editor.undo();
    expect(editor.document.markers[0].timeUs).toBe(3_000_000);
    expect(editor.document.connections).toHaveLength(1);
  });
  it('轨道分组移动后时间锚点跟随位置，源时间不被改写', () => {
    const document = newDocument('轨道分组');
    const assetId = crypto.randomUUID(), mediaId = crypto.randomUUID(), textId = crypto.randomUUID();
    document.assets.push({ id: assetId, name: 'sample.wav', path: 'assets/sample.wav', kind: 'audio', status: 'ready', durationUs: 8_000_000 });
    document.objects.push({ id: mediaId, kind: 'media', assetId, x: 10, y: 20, width: 100, height: 80, groupId: null, inUs: 0, outUs: 8_000_000, pixelsPerSecond: 20 });
    document.objects.push({ id: textId, kind: 'text', x: 250, y: 20, width: 120, height: 60, groupId: null, text: canvasTextFromPlainText('说明'), fontSize: 16, color: '#000', align: 'left' });
    const editor = new Editor(document);
    editor.annotateMarker(editor.addMarker(mediaId, 3_000_000), textId);
    editor.group([mediaId, textId]);
    editor.moveObject(textId, 290, 50);
    expect(editor.document.markers[0].timeUs).toBe(3_000_000);
    expect(resolveAnchor(editor.document, editor.document.connections[0].from)).toEqual({ x: 110, y: 90 });
    expect(editor.document.objects.find(item => item.id === mediaId)).toMatchObject({ x: 50, y: 50 });
    editor.undo();
    expect(resolveAnchor(editor.document, editor.document.connections[0].from)).toEqual({ x: 70, y: 60 });
  });
  it('复制嵌套分组会复制全部成员、层级和内部连线', () => {
    const document = newDocument('复制分组');
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    ids.forEach((id, index) => document.objects.push({ id, kind: 'rectangle', x: index * 100, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' }));
    const editor = new Editor(document);
    editor.group(ids);
    editor.group(ids.slice(0, 2));
    editor.execute(draft => { draft.connections.push({ id: crypto.randomUUID(), from: { kind: 'object', objectId: ids[0] }, to: { kind: 'object', objectId: ids[1] }, routing: 'straight' }); });
    const copied = editor.duplicateObjects([ids[0]]);
    expect(copied).toHaveLength(2);
    expect(editor.document.objects).toHaveLength(5);
    expect(editor.document.objects.find(item => item.id === ids[2])?.x).toBe(200);
    const clones = editor.document.objects.filter(item => copied.includes(item.id));
    expect(clones.map(item => item.x)).toEqual([32, 132]);
    expect(clones[0].groupId).toBe(clones[1].groupId);
    const cloneGroup = editor.document.groups.find(group => group.id === clones[0].groupId);
    expect(cloneGroup?.parentId).not.toBeNull();
    expect(editor.document.connections).toHaveLength(2);
    expect(editor.document.connections[1].from).toMatchObject({ kind: 'object', objectId: copied[0] });
    editor.undo();
    expect(editor.document.objects).toHaveLength(3);
    expect(editor.document.groups).toHaveLength(2);
    expect(editor.document.connections).toHaveLength(1);
  });
  it('连接线可改样式、撤销与删除', () => {
    const document = newDocument('连线');
    const a = crypto.randomUUID(), b = crypto.randomUUID();
    document.objects.push({ id: a, kind: 'rectangle', x: 0, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' });
    document.objects.push({ id: b, kind: 'rectangle', x: 100, y: 0, width: 50, height: 50, groupId: null, fill: '#fff', stroke: '#000' });
    document.connections.push({ id: crypto.randomUUID(), from: { kind: 'object', objectId: a }, to: { kind: 'object', objectId: b }, routing: 'straight' });
    const editor = new Editor(document);
    const id = editor.document.connections[0].id;
    editor.updateConnectionStyle(id, { dash: 'custom', customDash: [9, 3, 2, 3], endHead: 'open', opacity: .6, headSize: 18, label: '转场' });
    expect(editor.document.connections[0].style).toMatchObject({ dash: 'custom', endHead: 'open', opacity: .6, headSize: 18, label: '转场' });
    editor.duplicateObjects([a, b]);
    expect(editor.document.connections[1].style).toEqual(editor.document.connections[0].style);
    editor.undo();
    editor.undo();
    expect(editor.document.connections[0].style).toBeUndefined();
    editor.deleteConnections([id]);
    expect(editor.document.connections).toHaveLength(0);
    editor.undo();
    expect(editor.document.connections).toHaveLength(1);
  });
  it('多选对象可对齐和分布，整次排列只形成一次撤销', () => {
    const document = newDocument('排列');
    const ids = [crypto.randomUUID(), crypto.randomUUID(), crypto.randomUUID()];
    document.objects.push(
      { id: ids[0], kind: 'rectangle', x: 0, y: 30, width: 20, height: 20, groupId: null, fill: '#fff', stroke: '#000' },
      { id: ids[1], kind: 'rectangle', x: 70, y: 0, width: 30, height: 30, groupId: null, fill: '#fff', stroke: '#000' },
      { id: ids[2], kind: 'rectangle', x: 160, y: 50, width: 40, height: 40, groupId: null, fill: '#fff', stroke: '#000' }
    );
    const editor = new Editor(document);
    editor.arrangeObjects(ids, 'top');
    expect(editor.document.objects.map(object => object.y)).toEqual([0, 0, 0]);
    editor.undo();
    expect(editor.document.objects.map(object => object.y)).toEqual([30, 0, 50]);
    editor.arrangeObjects(ids, 'distribute-x');
    expect(editor.document.objects.map(object => object.x)).toEqual([0, 75, 160]);
  });
});
